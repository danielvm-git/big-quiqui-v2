#!/usr/bin/env bash
# story: e06s03
# coverage-map.sh — which tests exist for which module, and what has none.
#
# This project has no line-coverage instrumentation (GUT does not provide it, and there
# is no lcov/gcovr for GDScript). Rather than invent a percentage, this maps the real
# thing: for each production script, the test files that exercise it — by class name
# when it declares one, by the scene it builds when it is a builder, else by file name.
# A module with no reference is a gap, and the gaps are what a reviewer reads.
#
#   bash scripts/coverage-map.sh           # print the map
#   bash scripts/coverage-map.sh --write   # regenerate specs/tech-architecture/COVERAGE_MAP_LATEST.md
set -uo pipefail
cd "$(dirname "$0")/.."

OUT="specs/tech-architecture/COVERAGE_MAP_LATEST.md"

# How a module is found from a test: class_name > built scene > file basename.
identifier_for() {
  local module="$1" class scene
  class="$(sed -n 's/^class_name \([A-Za-z0-9_]*\).*/\1/p' "$module" | head -1)"
  if [ -n "$class" ]; then
    printf '%s' "$class"
    return
  fi
  scene="$(sed -n 's/^const SCENE_PATH: String = "\(res:\/\/[^"]*\)".*/\1/p' "$module" | head -1)"
  if [ -n "$scene" ]; then
    printf '%s' "$(basename "$scene")"
    return
  fi
  # Autoloads declare no class_name: godot names the node after the file, in PascalCase,
  # and tests reach them as `/root/SceneManager`.
  basename "$module" .gd | awk -F_ '{for (i = 1; i <= NF; i++) printf toupper(substr($i, 1, 1)) substr($i, 2)}'
}

render() {
  printf '# Coverage map — module to test references\n\n'
  printf '<!-- story: e06s03 -->\n'
  printf '**Generated by** `bash scripts/coverage-map.sh --write`. No line-coverage instrumentation\n'
  printf 'exists for GDScript in this project, so this is the honest substitute: for every\n'
  printf 'production script, the tests that exercise it, and the gaps.\n\n'
  printf '| Module | Found through | Tests referencing it |\n|---|---|---|\n'
  local gaps=0 modules=0 indirect=0
  while IFS= read -r module; do
    modules=$((modules + 1))
    local id hits
    id="$(identifier_for "$module")"
    local file_hits
    hits="$(grep -rlF "$id" game/tests --include=*.gd 2>/dev/null | wc -l | tr -d ' ')"
    # a test may name the module by its path instead of its class (`res://tools/type_gate.gd`)
    file_hits="$(grep -rlF "$(basename "$module")" game/tests --include=*.gd 2>/dev/null | wc -l | tr -d ' ')"
    [ "$file_hits" -gt "$hits" ] && hits="$file_hits"
    if [ "$hits" = "0" ]; then
      # Indirect: another production script that IS tested references this one, or the
      # module is an autoload reached by node path (`/root/SceneManager`).
      local via
      via="$(grep -rlF "$id" game/scripts --include=*.gd 2>/dev/null | grep -vF "$module" | head -1)"
      if [ -n "$via" ]; then
        printf '| `%s` | `%s` | indirect via `%s` |\n' "$module" "$id" "$(basename "$via")"
        indirect=$((indirect + 1))
        continue
      fi
      printf '| `%s` | `%s` | **GAP** |\n' "$module" "$id"
      gaps=$((gaps + 1))
    else
      printf '| `%s` | `%s` | %s |\n' "$module" "$id" "$hits"
    fi
  done < <(find game/scripts game/tools -name '*.gd' | sort)
  printf '\n**%s production scripts, %s gap(s).** Gaps are reviewed at each epic gate; a gap is\n' "$modules" "$gaps"
  printf 'acceptable only when the module is impossible to exercise headless (documented here).\n'
}

if [ "${1:-}" = "--write" ]; then
  render > "$OUT"
  echo "wrote $OUT"
else
  render
fi
