#!/usr/bin/env bash
# story: e06s03
# churn-rank.sh — the files that change most, ranked. Hotspots, not opinions.
#
# A file that changes often and carries risk is where review attention pays. The rank
# is commits-touching-the-file over the last N commits, with the size of the file and
# its test references alongside, so "big and churning" stands out from "big and stable".
#
#   bash scripts/churn-rank.sh                 # top 15 over the whole history
#   bash scripts/churn-rank.sh 40              # top 15 over the last 40 commits
#   bash scripts/churn-rank.sh 0 --write       # regenerate specs/tech-architecture/HOTSPOTS_LATEST.md
set -uo pipefail
cd "$(dirname "$0")/.."

OUT="specs/tech-architecture/HOTSPOTS_LATEST.md"
LIMIT="${1:-0}"
MODE="${2:-}"

render() {
  local range="HEAD"
  [ "$LIMIT" != "0" ] && range="HEAD~${LIMIT}..HEAD"
  printf '# Hotspots — churn-ranked\n\n'
  printf '<!-- story: e06s03 -->\n'
  printf '**Generated by** `bash scripts/churn-rank.sh 0 --write` over `%s`.\n' "$range"
  printf 'Churn is the number of commits touching the file; `lines` is its current size;\n'
  printf '`tests` is how many test files name it. Review pays where churn and size meet.\n\n'
  printf '| Rank | File | Commits | Lines | Tests |\n|---|---|---|---|---|\n'
  git log --no-merges --pretty=format: --name-only "$range" \
    | grep -E '^(game|scripts|\.github)/' | grep -vE '\.import$|\.uid$' \
    | sort | uniq -c | sort -rn | head -15 \
    | awk '{count=$1; path=$2; cmd="wc -l < \"" path "\" 2>/dev/null"; cmd | getline lines; close(cmd);
            base=path; sub(/.*\//, "", base); sub(/\.gd$/, "", base);
            pascal=base; gsub(/_/, " ", pascal); n=split(pascal, parts, " "); pascal="";
            for (i = 1; i <= n; i++) pascal = pascal toupper(substr(parts[i], 1, 1)) substr(parts[i], 2);
            cmd2="grep -rliF -e \"" base "\" -e \"" pascal "\" game/tests --include=*.gd 2>/dev/null | wc -l";
            cmd2 | getline tests; close(cmd2);
            printf "| %d | `%s` | %d | %d | %d |\n", NR, path, count, lines, tests}'
  printf '\n**Read this as:** a high-churn, high-line file is where the next bug lives; a\n'
  printf 'high-churn, low-test file is where the next regression goes unnoticed.\n'
}

if [ "$MODE" = "--write" ]; then
  render > "$OUT"
  echo "wrote $OUT"
else
  render
fi
